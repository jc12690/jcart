(function(){
  "use strict";
  var RM = matchMedia("(prefers-reduced-motion: reduce)").matches;
  var root = document.documentElement;
  var $ = function(id){ return document.getElementById(id); };
  function esc(s){ return String(s).replace(/[&<>"]/g, function(c){
    return {"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;"}[c]; }); }
  function two(n){ return (n < 10 ? "0" : "") + n; }
  function isClip(src){ return /\.(mp4|m4v|mov|webm)$/i.test(src); }

  /* ---------- theme: the same jc-theme preference as the rest of the site ---------- */
  var tog = $("themeTog");
  function syncTog(){
    var light = root.getAttribute("data-theme") === "light";
    var label = light ? "Switch to dark mode" : "Switch to light mode";
    tog.setAttribute("aria-pressed", light ? "true" : "false");
    tog.setAttribute("aria-label", label); tog.title = label;
  }
  tog.addEventListener("click", function(){
    var light = root.getAttribute("data-theme") === "light";
    if(light) root.removeAttribute("data-theme"); else root.setAttribute("data-theme", "light");
    try{ localStorage.setItem("jc-theme", light ? "dark" : "light"); }catch(e){}
    syncTog();
  });
  syncTog();

  /* ---------- clock ---------- */
  function tick(){
    $("clock").textContent = new Date().toLocaleTimeString("en-US",
      {timeZone:"America/New_York", hour:"2-digit", minute:"2-digit", hour12:false}) + " NY";
  }
  tick(); setInterval(tick, 15000);

  /* ---------- clips: silent loops that play only while on screen ----------
     Same rule as the Pilates site: nothing decodes off screen, and with reduced
     motion nothing plays; each clip shows its poster instead. */
  var onScreen = "IntersectionObserver" in window ? new IntersectionObserver(function(entries){
    entries.forEach(function(e){
      var v = e.target;
      if(e.isIntersecting && !paused){
        if(v.preload === "none") v.preload = "auto";
        var p = v.play(); if(p && p.catch) p.catch(function(){});
      } else { v.pause(); }
    });
  }, {threshold:0.2}) : null;
  var paused = false;   /* true while the viewer is open */
  function watch(v){
    if(RM) return;
    if(onScreen) onScreen.observe(v);
    else { var p = v.play(); if(p && p.catch) p.catch(function(){}); }
  }

  /* ---------- the work: every photo on the page, no clicks or hovers needed ---------- */
  var ITEMS = [];   /* page order, for the viewer */
  var work = $("work");
  work.innerHTML = JC_MODELING.map(function(b, bi){
    var credit = (b.photography || []).map(function(c){
      return '<a href="' + esc(c[1]) + '" target="_blank" rel="noopener">' + esc(c[0]) +
        ' <span aria-hidden="true">&#8599;</span></a>';
    }).join(", ");
    var many = b.collections.length > 1;
    return '<article class="client">' +
      '<header class="client-head">' +
        '<p class="eyebrow"><span class="br">[' + two(bi + 2) + ']</span>' +
          (many ? b.collections.length + " collections" : esc(b.collections[0].label)) + "</p>" +
        "<h2>" + esc(b.brand) + "</h2>" +
        (credit ? '<p class="credit">Photography: ' + credit + "</p>" : "") +
      "</header>" +
      b.collections.map(function(c){
        var count = c.items.length;
        var shots = c.items.map(function(it, k){
          var i = ITEMS.length, clip = isClip(it.src);
          var cap = b.brand + " · " + c.label;
          ITEMS.push({ src: it.src, full: it.full || it.src, poster: it.poster, w: it.w, h: it.h, clip: clip, cap: cap });
          var label = (clip ? "Behind the scenes, " : "Photo " + (k + 1) + " of " + count + ", ") + b.brand + ", " + c.label;
          var ratio = "aspect-ratio:" + it.w + " / " + it.h;
          return '<button class="shot" type="button" data-i="' + i + '" data-r="' + (it.h / it.w).toFixed(4) +
            '" aria-haspopup="dialog" aria-label="View larger: ' + esc(label) + '">' +
            (clip
              ? '<video muted loop playsinline preload="none" poster="' + esc(it.poster || "") + '" style="' + ratio +
                '" aria-hidden="true"><source src="' + esc(it.src) + '" type="video/mp4"></video><span class="tag">BTS</span>'
              : '<img src="' + esc(it.src) + '" width="' + it.w + '" height="' + it.h + '" style="' + ratio +
                '" alt="" loading="lazy" decoding="async">') +
            "</button>";
        }).join("");
        return '<section class="col">' + (many ? '<h3 class="col-label">' + esc(c.label) + "</h3>" : "") +
          '<div class="grid">' + shots + "</div></section>";
      }).join("") +
      "</article>";
  }).join("");

  /* Masonry: each shot goes into whichever column is shortest, so the first
     photos run across the top and the columns end close to even. Sizes come
     from the list above, so nothing jumps as the photos load. */
  var grids = [].slice.call(work.querySelectorAll(".grid"));
  var shotsByGrid = grids.map(function(g){ return [].slice.call(g.children); });
  var cols = 0;
  function layout(){
    var w = work.clientWidth, n = w >= 980 ? 3 : 2;
    if(n === cols) return;
    cols = n;
    grids.forEach(function(g, gi){
      var columns = [], heights = [];
      for(var c = 0; c < n; c++){
        var col = document.createElement("div"); col.className = "gcol";
        columns.push(col); heights.push(0);
      }
      shotsByGrid[gi].forEach(function(s){
        var c = heights.indexOf(Math.min.apply(null, heights));
        columns[c].appendChild(s); heights[c] += +s.getAttribute("data-r") + 0.02;
      });
      g.textContent = "";
      columns.forEach(function(col){ g.appendChild(col); });
    });
  }
  layout();
  addEventListener("resize", layout);

  [].forEach.call(document.querySelectorAll("video"), watch);

  /* ---------- the viewer: plain and immediate ----------
     No mosaic and no fade-in here: someone deciding on a booking should see the
     photo the moment they open it. The page's copy shows at once, and the
     full-size file replaces it as soon as it arrives. */
  var lb = $("lb"), screen = $("lbScreen"), lbCap = $("lbCap"), lbCount = $("lbCount"), lbPlay = $("lbPlay");
  var at = 0, media = null, opener = null;
  function fit(it){
    var phone = innerWidth <= 700;
    var maxW = Math.min(innerWidth - (phone ? 46 : 190), 1600), maxH = innerHeight - (phone ? 210 : 150);
    var s = Math.min(maxW / it.w, maxH / it.h);
    screen.style.width = Math.round(it.w * s) + "px";
    screen.style.height = Math.round(it.h * s) + "px";
  }
  function syncPlay(){ if(media && media.tagName === "VIDEO") lbPlay.textContent = media.paused ? "Play" : "Pause"; }
  function drop(){
    if(!media) return;
    if(media.tagName === "VIDEO"){ media.pause(); media.removeAttribute("src"); media.load(); }
    media.remove(); media = null;
  }
  function show(i){
    at = (i + ITEMS.length) % ITEMS.length;
    var it = ITEMS[at];
    drop();
    var m;
    if(it.clip){
      m = document.createElement("video");
      m.muted = true; m.loop = true; m.playsInline = true; m.setAttribute("playsinline", "");
      if(it.poster) m.poster = it.poster;
      m.src = it.src;
      m.addEventListener("play", syncPlay); m.addEventListener("pause", syncPlay);
      if(!RM){ var p = m.play(); if(p && p.catch) p.catch(function(){}); }
    } else {
      m = new Image(); m.alt = "Jarred Carter, " + it.cap; m.decoding = "async"; m.src = it.full;
    }
    m.className = "lb-media";
    /* the page's own copy sits underneath, so the frame is never empty */
    screen.style.backgroundImage = 'url("' + (it.clip ? it.poster || "" : it.src) + '")';
    screen.appendChild(m); media = m;
    fit(it);
    lbCap.textContent = it.cap;
    lbCount.textContent = two(at + 1) + " / " + two(ITEMS.length);
    lbPlay.hidden = !it.clip; syncPlay();
  }
  function open(i, from){
    opener = from;
    paused = true;
    [].forEach.call(document.querySelectorAll("main video"), function(v){ v.pause(); });
    lb.hidden = false;
    document.body.classList.add("lb-lock");
    show(i);
    $("lbX").focus();
  }
  function close(){
    lb.hidden = true;
    document.body.classList.remove("lb-lock");
    drop();
    paused = false;
    if(onScreen && !RM){   /* let the page's clips pick up where they were */
      [].forEach.call(document.querySelectorAll("main video"), function(v){ onScreen.unobserve(v); onScreen.observe(v); });
    }
    if(opener && opener.focus) opener.focus();
  }
  work.addEventListener("click", function(e){
    var s = e.target.closest && e.target.closest(".shot");
    if(s) open(+s.getAttribute("data-i"), s);
  });
  $("lbX").addEventListener("click", close);
  $("lbPrev").addEventListener("click", function(){ show(at - 1); });
  $("lbNext").addEventListener("click", function(){ show(at + 1); });
  lbPlay.addEventListener("click", function(){
    if(!media) return;
    if(media.paused){ var p = media.play(); if(p && p.catch) p.catch(function(){}); } else media.pause();
  });
  lb.addEventListener("click", function(e){ if(e.target === lb) close(); });
  document.addEventListener("keydown", function(e){
    if(lb.hidden) return;
    if(e.key === "Escape"){ e.preventDefault(); close(); }
    else if(e.key === "ArrowLeft"){ e.preventDefault(); show(at - 1); }
    else if(e.key === "ArrowRight"){ e.preventDefault(); show(at + 1); }
    else if(e.key === "Tab"){
      var f = [].filter.call(lb.querySelectorAll("button"), function(b){ return !b.hidden; });
      var k = f.indexOf(document.activeElement);
      if(e.shiftKey && k <= 0){ e.preventDefault(); f[f.length - 1].focus(); }
      else if(!e.shiftKey && k === f.length - 1){ e.preventDefault(); f[0].focus(); }
    }
  });
  var sx = null, sy = 0;
  screen.addEventListener("pointerdown", function(e){ sx = e.clientX; sy = e.clientY; });
  screen.addEventListener("pointerup", function(e){
    if(sx === null) return;
    var dx = e.clientX - sx, dy = e.clientY - sy; sx = null;
    if(Math.abs(dx) > 44 && Math.abs(dx) > Math.abs(dy) * 1.4) show(at + (dx < 0 ? 1 : -1));
  });
  screen.addEventListener("pointercancel", function(){ sx = null; });
  addEventListener("resize", function(){ if(!lb.hidden) fit(ITEMS[at]); });

  /* ---------- the address: shown as text, Copy as a convenience ---------- */
  $("copy").addEventListener("click", function(){
    var b = this, addr = $("addr").textContent;
    function done(){ b.textContent = "Copied"; setTimeout(function(){ b.textContent = "Copy"; }, 1600); }
    function fallback(){ var s = getSelection(), r = document.createRange(); r.selectNodeContents($("addr")); s.removeAllRanges(); s.addRange(r); b.textContent = "Selected"; }
    try{ navigator.clipboard.writeText(addr).then(done, fallback); }catch(e){ fallback(); }
  });
})();
